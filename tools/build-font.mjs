// Converts Hershey single-stroke SVG fonts (from the `hersheytext` npm package)
// into js/font.js. Usage: node tools/build-font.mjs <path-to-svg_fonts-dir>
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
const FONTS = { print: 'HersheySans1.svg', script: 'HersheyScript1.svg' };
const unescape = (s) =>
  s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

const out = {};
for (const [name, file] of Object.entries(FONTS)) {
  const svg = fs.readFileSync(path.join(dir, file), 'utf8');
  const glyphs = {};
  for (const m of svg.matchAll(/<glyph\s+([^>]*?)\/>/g)) {
    const attr = (k) => (m[1].match(new RegExp(`${k}="([^"]*)"`)) || [])[1];
    const ch = unescape(attr('unicode') ?? '');
    if (ch.length !== 1 || ch.charCodeAt(0) < 32 || ch.charCodeAt(0) > 126) continue;
    const strokes = [];
    const toks = (attr('d') ?? '').trim().split(/\s+/).filter(Boolean);
    for (let i = 0; i < toks.length; ) {
      const cmd = toks[i++];
      if (cmd !== 'M' && cmd !== 'L') throw new Error(`unexpected path command ${cmd} in ${file}`);
      const pt = [Math.round(+toks[i++]), Math.round(+toks[i++])];
      if (cmd === 'M') strokes.push([pt]); else strokes[strokes.length - 1].push(pt);
    }
    // each stroke flattened to "x,y x,y"; units are 1/1000 em, y up from the baseline
    glyphs[ch] = [Math.round(+attr('horiz-adv-x')), strokes.map((s) => s.map((p) => p.join(',')).join(' '))];
  }
  out[name] = glyphs;
}

const banner = `// Generated by tools/build-font.mjs — do not edit.
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
// U. S. National Bureau of Standards. The format of the font data was originally created by
// James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821.
// SVG conversion by Windell H. Oskay (evilmadscientist.com), via the hersheytext package.
// Glyph: [advance, [stroke, ...]] with stroke = "x,y x,y ..." in 1/1000 em, y up.
`;
fs.writeFileSync(new URL('../js/font.js', import.meta.url), `${banner}export const FONTS = ${JSON.stringify(out)};\n`);
for (const [n, g] of Object.entries(out)) console.log(n, Object.keys(g).length, 'glyphs');
